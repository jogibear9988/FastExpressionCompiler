using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace FastExpressionCompiler.TestRegistrationGenerator;

[Generator]
public sealed class FixtureGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        foreach (var ns in new[] { "FastExpressionCompiler.UnitTests", "FastExpressionCompiler.LightExpression.UnitTests" })
        {
            var fixtures = context.SyntaxProvider.ForAttributeWithMetadataName(
                ns + ".RunTestXAttribute",
                (node, _) => node is TypeDeclarationSyntax,
                (attribute, _) => ((INamedTypeSymbol)attribute.TargetSymbol)
                    .ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
            context.RegisterSourceOutput(fixtures.Collect(), (output, types) => Emit(output, ns, types));
        }
    }

    private static void Emit(SourceProductionContext output, string ns, ImmutableArray<string> types)
    {
        if (types.IsDefaultOrEmpty) return;
        var fixtures = types.Distinct(StringComparer.Ordinal).OrderBy(x => x, StringComparer.Ordinal).ToArray();
        var runType = ns.Substring(0, ns.Length - ".UnitTests".Length) + ".TestRun";
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.Append("namespace ").AppendLine(ns);
        source.AppendLine("{");
        source.AppendLine("    public static partial class RegisteredTestX");
        source.AppendLine("    {");
        source.Append("        public static partial void Run(global::").Append(runType).AppendLine(" tests)");
        source.AppendLine("        {");
        foreach (var fixture in fixtures)
            source.Append("            tests.Run(new ").Append(fixture).AppendLine("());");
        source.AppendLine("        }");
        source.AppendLine("        public static global::System.Type[] GetFixtureTypes() => new global::System.Type[]");
        source.AppendLine("        {");
        foreach (var fixture in fixtures)
            source.Append("            typeof(").Append(fixture).AppendLine("),");
        source.AppendLine("        };");
        source.AppendLine("    }");
        source.AppendLine("}");
        output.AddSource(ns + ".RegisteredTestX.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }
}
